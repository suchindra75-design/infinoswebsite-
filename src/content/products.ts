export interface PlaceholderValue {
  value: string
  placeholder: boolean
}

export interface ExplodeSpec {
  dir: [number, number, number]
  distance: number
  rotate?: [number, number, number]
}

/** Opening sequence stages, in order. The inner box lid only opens once the box is out (photos WA0026/28/29). */
export type OpenStage = 'flap' | 'lid' | 'drop' | 'boxOut' | 'boxLid'

export interface OpenMotion {
  stage: OpenStage
  /** hinge rotation (radians) about the layer pivot at stage amount 1 */
  rotate?: [number, number, number]
  /** translation in model metres at stage amount 1 */
  translate?: [number, number, number]
}

export interface ProductComponentSpec {
  id: string
  nodeName: string
  label: string
  role: string
  placeholder: boolean
  priority: number
  basePosition: [number, number, number]
  explode: ExplodeSpec
  open?: OpenMotion[]
  metadata?: Record<string, string>
  labelSide: 'left' | 'right'
}

export interface Product {
  slug: string
  name: string
  namePlaceholder: boolean
  tagline: string
  description: string
  status: 'conceptual-placeholder'
  model: {
    source: string | null
    format: 'GLB'
    placeholder: boolean
    note: string
    targetHeightMeters: number
    targetHeightPlaceholder: boolean
    display: {
      nodeName: string
      anchor: [number, number, number]
      placeholder: boolean
    }
  }
  /** OLED reading as photographed (WA0016) — illustrative, not a specification */
  displayReading: PlaceholderValue
  components: ProductComponentSpec[]
  /** Layers of the REAL replica GLB (public/models/t1.glb). `components` stays as the placeholder-geometry fallback. */
  modelComponents: ProductComponentSpec[]
}

